// tools/gen-signage.mjs
//
// Every sign in this museum is cut up by the same tokenizer the museum is about.
// Doing that in the browser would mean every page downloading 1.1 MB of merge
// ranks in order to draw its own name, so the cuts are made once, here, and
// written to assets/signage.js.
//
// This is not a build step, and nothing needs to run for the site to work. The
// script exists so that the header cells are checkable: run it, and the file it
// writes should be byte-identical to the one already committed.
//
//   node tools/gen-signage.mjs
//   node tools/gen-signage.mjs --check    (exit 1 if the committed file is stale)

import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { load, tokenize, ENCODING } from '../lib/tokenizer.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'assets', 'signage.js');

// Every string that appears as a sign anywhere in the building.
const SIGNS = [
  'Seams',
  'The Garden of Forking Paths',
  'Temperature',
  'The Anaphora Room',
  'The Context Window',
  'The Chorus',
  'Byte-Pair Playback',
  'Floor Plan',
  'Machinery',
];

await load();

const signs = {};
for (const sign of SIGNS) {
  const { tokens } = tokenize(sign);
  signs[sign] = tokens.map((t) => t.text);
}

const body =
  `// Generated by tools/gen-signage.mjs. Do not edit by hand.\n` +
  `//\n` +
  `// These are the museum's signs, cut into tokens by the real ${ENCODING} merge\n` +
  `// table. Each array is one sign; each string is one token. The leading spaces\n` +
  `// are not formatting — they belong to the tokens.\n` +
  `\n` +
  `export const ENCODING = ${JSON.stringify(ENCODING)};\n` +
  `\n` +
  `export default ${JSON.stringify(signs, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const existing = readFileSync(out, 'utf8');
  if (existing !== body) {
    console.error('assets/signage.js is stale. Run: node tools/gen-signage.mjs');
    process.exit(1);
  }
  console.log('assets/signage.js is current.');
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out}`);
  for (const cells of Object.values(signs)) {
    console.log(`  ${cells.map((c) => `[${c}]`).join('')}`);
  }
}
